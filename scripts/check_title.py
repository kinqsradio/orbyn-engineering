#!/usr/bin/env python3
"""Checks that a pull request or issue title names its kind and says what it does.

The form is `type(scope): summary`, the same one Conventional Commits uses, so a
title reads like the commit it becomes:

    fix(web): keep the composer focused after send
    feat: publish an agent page in the conversation
    docs: require conventional titles for pull requests and issues

Run with `--title` and `--kind`; the exit status is 0 when the title fits, and
otherwise 1 with one line per problem. `--kind issue` also accepts `question`,
because an issue may ask something that no commit will fix.
"""

from __future__ import annotations

import argparse
import re
import sys

MAX_TITLE_CHARS = 72

TYPES = (
    "feat",
    "fix",
    "docs",
    "test",
    "refactor",
    "perf",
    "build",
    "ci",
    "chore",
    "style",
    "revert",
)

# An optional scope, an optional breaking-change marker, then the summary. The
# scope is lowercase letters, digits and hyphens, so it reads as one word.
TITLE = re.compile(
    r"^(?P<type>[a-z]+)"
    r"(?:\((?P<scope>[a-z0-9][a-z0-9-]*)\))?"
    r"(?P<breaking>!)?"
    r": (?P<summary>.+)$"
)


def allowed_types(kind: str) -> tuple[str, ...]:
    return (*TYPES, "question") if kind == "issue" else TYPES


def check(title: str, kind: str) -> list[str]:
    """Every reason the title does not fit, as sentences; empty when it fits."""
    problems: list[str] = []
    text = title.strip()
    if not text:
        return ["The title is empty."]
    if not text[0].islower() and not text[0].isdigit() and text[0] != "!":
        problems.append(
            "The title starts with a capital letter; a sentence case title such as "
            "'Fix the composer' is not this form."
        )
    match = TITLE.match(text)
    if match is None:
        problems.append(
            "The title is not `type(scope): summary`, such as "
            "'fix(web): keep the composer focused after send'."
        )
        return problems
    name = match.group("type")
    if name not in allowed_types(kind):
        problems.append(
            f"`{name}` is not a kind. Use one of: {', '.join(allowed_types(kind))}."
        )
    summary = match.group("summary").strip()
    if len(summary) < 3:
        problems.append("The summary is too short to say what changes.")
    if summary and summary[0].isupper():
        problems.append("The summary starts with a capital letter; use lowercase.")
    if summary.endswith("."):
        problems.append("The summary ends with a full stop; titles do not.")
    if summary.startswith(":") or summary.startswith("-"):
        problems.append("The summary starts with punctuation.")
    if re.search(r"\s{2,}", summary):
        problems.append("The summary has a run of spaces in it.")
    if len(text) > MAX_TITLE_CHARS:
        problems.append(
            f"The title is {len(text)} characters; keep it to {MAX_TITLE_CHARS}."
        )
    # Attribution, not vocabulary: a summary may talk about an engine or a model as
    # the subject ("show the claude usage limit"), but never credit a tool for the
    # change. Judgement still belongs to review; this only catches the plain cases.
    if "co-authored-by" in text.lower() or re.search(
        r"\b(?:by|with|using|via|generated by|written by) "
        r"(?:claude|codex|cursor|gpt|copilot|an? (?:ai|assistant|agent|model))\b",
        summary,
        re.IGNORECASE,
    ):
        problems.append(
            "The title credits a tool or an assistant; record AI use in the AI usage "
            "section of the body instead."
        )
    return problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Check a pull request or issue title.")
    parser.add_argument("--title", required=True, help="the title to check")
    parser.add_argument(
        "--kind",
        choices=("pull-request", "issue"),
        default="pull-request",
        help="which set of kinds the title may use",
    )
    arguments = parser.parse_args(argv)
    problems = check(arguments.title, "issue" if arguments.kind == "issue" else "pr")
    if not problems:
        print("Title fits the convention.")
        return 0
    print(f"Pull request and issue titles follow `type(scope): summary`.")
    for problem in problems:
        print(f"- {problem}", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
